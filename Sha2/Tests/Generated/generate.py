"""Writes `digests.txt`, the digests `Sha2/Tests.lean` checks the FIPS 180-4 functions against.

Each line is `<hasher> pattern <length> <digest>`: the digest, by Python's `hashlib` (OpenSSL), not
by the crate or the Lean definitions, of the message of `<length>` bytes `i % 251` for `i` from 0.
Run from the repository root: python3 Sha2/Tests/Generated/generate.py
"""

import hashlib
from pathlib import Path

HASHERS = ["sha224", "sha256", "sha384", "sha512", "sha512_224", "sha512_256"]
LENGTHS = [0, 1, 2, 3, 55, 56, 57, 63, 64, 65, 111, 112, 113, 119, 120, 127, 128, 129, 191, 192, 200,
           255, 256, 257, 300, 1000]


def main():
    lines = ["# generated by generate.py from Python's hashlib (OpenSSL); see its docstring"]
    for name in HASHERS:
        for length in LENGTHS:
            message = bytes(i % 251 for i in range(length))
            lines.append(f"{name} pattern {length} {hashlib.new(name, message).hexdigest()}")
    Path(__file__).with_name("digests.txt").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
